#!/usr/bin/env node
// build-docs-manifest.js
// Scans assets/pdfs/{resume,cv,transcript} and writes js/docs-data.js — the
// manifest js/main.js reads to point the "Download Resume / CV / Transcript"
// buttons at the newest file per document type and language.
//
// Dev-side tooling only (Node built-ins, no npm). It is run by the pre-commit
// hook in .githooks/ and can be run by hand to preview:
//     node scripts/build-docs-manifest.js
// The site itself still deploys as plain static files — this is NOT a build step.
//
// Filename pattern, every type (anything else is ignored with a warning):
//   "<en|es> Gideon Ong <Resume|CV|Transcript> <YYYYMMDD>.pdf"
// Transcript PDFs are produced by scripts/transcript/ (Python, dev-only — see its
// README); resume and CV PDFs are exported by hand.
//
// The output is stable (sorted keys, LF line endings) and only rewritten when
// its content changes, so commits stay clean. Always exits 0.

"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "js", "docs-data.js");
const PDF_DIR = "assets/pdfs";

// type → { dir, label, langs } — one slot per language for every type.
const TYPES = {
  resume: { dir: "resume", label: "Resume", langs: ["en", "es"] },
  cv: { dir: "cv", label: "CV", langs: ["en", "es"] },
  transcript: { dir: "transcript", label: "Transcript", langs: ["en", "es"] }
};

const warnings = [];
function warn(msg) { warnings.push(msg); }

function isValidDate(yyyymmdd) {
  const y = +yyyymmdd.slice(0, 4), m = +yyyymmdd.slice(4, 6), d = +yyyymmdd.slice(6, 8);
  if (m < 1 || m > 12 || d < 1 || d > 31) return false;
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

function scanType(typeName, type) {
  const dirRel = PDF_DIR + "/" + type.dir;
  const dirAbs = path.join(ROOT, dirRel);
  const newest = {}; // lang → { date, file }
  type.langs.forEach((s) => { newest[s] = null; });

  let files = [];
  try {
    files = fs.readdirSync(dirAbs, { withFileTypes: true }).filter((d) => d.isFile()).map((d) => d.name);
  } catch (e) {
    warn(`${dirRel}/ is missing or unreadable — ${typeName} has no files`);
    return newest;
  }

  const pattern = new RegExp("^(" + type.langs.join("|") + ") Gideon Ong " + escapeRe(type.label) + " (\\d{8})\\.pdf$");

  files.sort().forEach((name) => {
    if (name.startsWith(".")) return; // .gitkeep and friends
    const m = pattern.exec(name);
    if (!m) { warn(`${dirRel}/${name}: does not match the ${typeName} pattern — ignored`); return; }
    const lang = m[1];
    const date = m[2];
    if (!isValidDate(date)) { warn(`${dirRel}/${name}: "${date}" is not a real date — ignored`); return; }
    const entry = { date, file: dirRel + "/" + name };
    if (!newest[lang] || date > newest[lang].date) newest[lang] = entry;
  });
  return newest;
}

function build() {
  const docs = {};
  Object.keys(TYPES).sort().forEach((typeName) => {
    const found = scanType(typeName, TYPES[typeName]);
    const slot = {};
    Object.keys(found).sort().forEach((lang) => { slot[lang] = found[lang] ? found[lang].file : null; });
    docs[typeName] = slot;
  });
  return docs;
}

function render(docs) {
  const lines = [];
  lines.push("// GENERATED by scripts/build-docs-manifest.js — do not edit by hand.");
  lines.push("// Newest file per document type and language under assets/pdfs/. Re-generated by");
  lines.push("// the pre-commit hook (.githooks/pre-commit); run the script by hand to preview.");
  lines.push("// null = no file for that slot. js/main.js reads this for [data-doc-link] buttons.");
  lines.push("const DOCS = {");
  const typeNames = Object.keys(docs);
  typeNames.forEach((typeName, i) => {
    const slot = docs[typeName];
    const parts = Object.keys(slot).map((k) => `${k}: ${slot[k] === null ? "null" : JSON.stringify(slot[k])}`);
    lines.push(`  ${typeName}: { ${parts.join(", ")} }${i < typeNames.length - 1 ? "," : ""}`);
  });
  lines.push("};");
  return lines.join("\n") + "\n";
}

const docs = build();
const next = render(docs);
let prev = null;
try { prev = fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch (e) { prev = null; }

if (prev === next) {
  console.log("docs manifest: js/docs-data.js unchanged");
} else {
  fs.writeFileSync(OUT, next, "utf8");
  console.log("docs manifest: wrote js/docs-data.js");
}
Object.keys(docs).forEach((t) => {
  Object.keys(docs[t]).forEach((l) => { console.log(`  ${t}.${l}: ${docs[t][l] || "(none)"}`); });
});
warnings.forEach((w) => console.warn("warning: " + w));
process.exit(0);
